#!/usr/bin/env node
// node tools/build-family.js [--check]
// Regenerates EVERY copy of the design family from the canonical files; nothing generated is edited by hand.
//   design/family.css          ->  vue/_shared36/family.css, <WorkshopService>/dwc36/family.css (the CORE: what the service page draws too)
//   design/family-plugins.css  ->  vue/_shared36/family-plugins.css (the rules only the plugins use; the service page does not get it)
//   both (core, then plugins)  ->  src/_shared/05-family-css.js (the same CSS as a string for the JS pages, injected by
//                                  workshopInjectFamily() through workshopCss, as tests/theme-class.test.js demands)
//   vue/_shared36/theme.css    ->  <WorkshopService>/dwc36/theme.css (the same file without the import of family-plugins.css)
// The DWC 3.7 copies (vue/_shared/family.css, <WorkshopService>/dwc-src/family.css) are NOT generated any more: that line is paused and they stay as
// they were (the whole family in one file).
//   vue/_shared/plugin-colors.js -> vue/_shared36/plugin-colors.js, <WorkshopService>/dwc-src and dwc36
//   vue/_shared36/<file>       ->  <WorkshopService>/dwc36/<file> for every shared file the service page keeps as a twin (+ the new ones in TWIN_EXTRA)
// <WorkshopService> = env WORKSHOP_SERVICE_DIR, else the sibling ../WorkshopService (also from a git worktree of this repo); when it is not
// there only the copies of this repo are made.
// --check writes nothing and exits 1 when a copy is out of date (tests/family-design.test.js does the same comparison).
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const rel = (p) => path.relative(root, p).split(path.sep).join("/");

function serviceDir() {
  const cands = [];
  if (process.env.WORKSHOP_SERVICE_DIR) cands.push(process.env.WORKSHOP_SERVICE_DIR);
  cands.push(path.join(root, "..", "WorkshopService"));
  // a linked worktree lives in a folder nested inside <repo>: the service folder is a sibling of <repo>
  cands.push(path.join(root, "..", "..", "..", "..", "WorkshopService"));
  return cands.find((d) => fs.existsSync(path.join(d, "dwc-src"))) || null;
}

const FAMILY_PLUGINS_IMPORT = /^@import '\.\/family-plugins\.css';[^\n]*\n/m;
// the theme.css of the service page: the shared one without the import of the plugins part
const serviceTheme = (theme) => theme.replace(FAMILY_PLUGINS_IMPORT, "");
// the CSS of the JS pages: core, then plugins
const joinFamily = (core, plugins) => core.replace(/\r\n/g, "\n").replace(/\n+$/, "\n") + plugins.replace(/\r\n/g, "\n");

function jsModule(css) {
  const lines = css.replace(/\r\n/g, "\n").replace(/\n$/, "").split("\n");
  return [
    "      // GENERATED by tools/build-family.js from design/family.css + design/family-plugins.css -- do not edit (tests/family-design.test.js compares it).",
    "      // The design family for the JS pages (classes wf-*): page bar, menu, tabs, cards, buttons, notes. A page calls",
    "      // workshopInjectFamily() once; the style goes in once per page, through workshopCss (3.6 / 3.7 theme class).",
    "      var WORKSHOP_FAMILY_CSS = [",
    lines.map((l) => "        " + JSON.stringify(l)).join(",\n"),
    '      ].join("\\n");',
    "",
    "      function workshopInjectFamily() {",
    '        if (typeof document === "undefined" || !document.head || typeof document.getElementById !== "function") return;',
    '        if (document.getElementById("workshop-family-css")) return;',
    '        var st = document.createElement("style");',
    '        st.id = "workshop-family-css";',
    "        st.textContent = workshopCss(WORKSHOP_FAMILY_CSS);",
    "        document.head.appendChild(st);",
    "      }",
    "",
  ].join("\n");
}

function targets() {
  const css = fs.readFileSync(path.join(root, "design", "family.css"), "utf8");
  const plugins = fs.readFileSync(path.join(root, "design", "family-plugins.css"), "utf8");
  const colors = fs.readFileSync(path.join(root, "vue", "_shared", "plugin-colors.js"), "utf8");
  const out = [
    [path.join(root, "vue", "_shared36", "family.css"), css],
    [path.join(root, "vue", "_shared36", "family-plugins.css"), plugins],
    [path.join(root, "vue", "_shared36", "plugin-colors.js"), colors],
    [path.join(root, "src", "_shared", "05-family-css.js"), jsModule(joinFamily(css, plugins))],
  ];
  const svc = serviceDir();
  if (svc) {
    out.push([path.join(svc, "dwc36", "family.css"), css]);
    out.push([path.join(svc, "dwc36", "theme.css"), serviceTheme(fs.readFileSync(path.join(root, "vue", "_shared36", "theme.css"), "utf8"))]);
    // plugin-colors.js is still written to both folders (it is not part of the split)
    for (const d of ["dwc-src", "dwc36"]) out.push([path.join(svc, d, "plugin-colors.js"), colors]);
    for (const n of twinNames(svc)) out.push(twinTarget(svc, n));
  }
  return out;
}

// The twins of the service page (3.6): every file of vue/_shared36 that the page also keeps, byte for byte, plus the ones in TWIN_EXTRA that are new. The page's
// own versions (TWIN_DIFFERENT_ON_PURPOSE: its entry points, catalogs and the pieces it draws with its own texts) are never copied. Same list as tests/shared-copies.test.js
// (section 1b), which compares them; tests/layers.test.js does not judge the root of dwc36/, where the twins live.
const TWIN_DIFFERENT_ON_PURPOSE = new Set(["LedStrip.vue", "i18n-register.js", "index.js", "plugin-id.js", "WorkshopService.vue", "SideTabs.vue", "access-api.js", "family.css", "family-plugins.css", "theme.css", "plugin-colors.js"]);
const TWIN_EXTRA = ["arm-ms.js"];
// shared files that the service page keeps in another folder of dwc36/ (same bytes, the imports between them are './x.js' in both places)
const TWIN_MAP = { "unsaved-guard.js": "ui/unsaved-guard.js", "unsaved-mixin.js": "ui/unsaved-mixin.js" };
const SHARED36 = path.join(root, "vue", "_shared36");
function twinNames(svc) {
  const dir36 = path.join(svc, "dwc36");
  const names = fs.readdirSync(SHARED36).filter((n) => fs.statSync(path.join(SHARED36, n)).isFile() && !TWIN_DIFFERENT_ON_PURPOSE.has(n) && fs.existsSync(path.join(dir36, n)));
  for (const n of TWIN_EXTRA.concat(Object.keys(TWIN_MAP))) if (!names.includes(n)) names.push(n);
  return names.sort();
}
// [file, text]: the text is the shared file; when the copy only differs in line endings its own text is returned, so a checkout with CRLF is not "out of date"
function twinTarget(svc, name) {
  const src = fs.readFileSync(path.join(SHARED36, name), "utf8");
  const file = path.join(svc, "dwc36", TWIN_MAP[name] || name);
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  const lf = (t) => t.replace(/\r\n/g, "\n");
  return [file, cur !== null && lf(cur) === lf(src) ? cur : src];
}

if (require.main === module) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, text] of targets()) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (cur === text) continue;
    stale++;
    if (check) console.log("out of date: " + file);
    else {
      fs.writeFileSync(file, text);
      console.log("written: " + (file.startsWith(root) ? rel(file) : file));
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("family: all copies up to date");
}

module.exports = { serviceDir, targets, jsModule, joinFamily, serviceTheme, twinNames, twinTarget, TWIN_MAP, TWIN_DIFFERENT_ON_PURPOSE };
