#!/usr/bin/env node
// node tools/build-family.js [--check]
// Regenerates EVERY copy of the design family from the two canonical files; nothing generated is edited by hand.
//   design/family.css          ->  vue/_shared/family.css, vue/_shared36/family.css,
//                                  <WorkshopService>/dwc-src/family.css, <WorkshopService>/dwc36/family.css,
//                                  src/_shared/05-family-css.js (the same CSS as a string for the JS pages, injected by
//                                  workshopInjectFamily() through workshopCss, as tests/theme-class.test.js demands)
//   vue/_shared/plugin-colors.js -> vue/_shared36/plugin-colors.js, <WorkshopService>/dwc-src and dwc36
// <WorkshopService> = env WORKSHOP_SERVICE_DIR, else the sibling ../WorkshopService (also from a git worktree of this repo); when it is not
// there only the copies of this repo are made.
// --check writes nothing and exits 1 when a copy is out of date (tests/family-design.test.js does the same comparison).
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const rel = (p) => path.relative(root, p).split(path.sep).join("/");

function serviceDir() {
  const cands = [];
  if (process.env.WORKSHOP_SERVICE_DIR) cands.push(process.env.WORKSHOP_SERVICE_DIR);
  cands.push(path.join(root, "..", "WorkshopService"));
  // a worktree lives in <repo>/.claude/worktrees/<name>: the service folder is a sibling of <repo>
  cands.push(path.join(root, "..", "..", "..", "..", "WorkshopService"));
  return cands.find((d) => fs.existsSync(path.join(d, "dwc-src"))) || null;
}

function jsModule(css) {
  const lines = css.replace(/\r\n/g, "\n").replace(/\n$/, "").split("\n");
  return [
    "      // GENERATED by tools/build-family.js from design/family.css -- do not edit (tests/family-design.test.js compares it).",
    "      // The design family for the JS pages (classes wf-*): page bar, menu, tabs, cards, buttons, notes. A page calls",
    "      // workshopInjectFamily() once; the style goes in once per page, through workshopCss (3.6 / 3.7 theme class).",
    "      var WORKSHOP_FAMILY_CSS = [",
    lines.map((l) => "        " + JSON.stringify(l)).join(",\n"),
    '      ].join("\\n");',
    "",
    "      function workshopInjectFamily() {",
    '        if (typeof document === "undefined" || !document.head || typeof document.getElementById !== "function") return;',
    '        if (document.getElementById("workshop-family-css")) return;',
    '        var st = document.createElement("style");',
    '        st.id = "workshop-family-css";',
    "        st.textContent = workshopCss(WORKSHOP_FAMILY_CSS);",
    "        document.head.appendChild(st);",
    "      }",
    "",
  ].join("\n");
}

function targets() {
  const css = fs.readFileSync(path.join(root, "design", "family.css"), "utf8");
  const colors = fs.readFileSync(path.join(root, "vue", "_shared", "plugin-colors.js"), "utf8");
  const out = [
    [path.join(root, "vue", "_shared", "family.css"), css],
    [path.join(root, "vue", "_shared36", "family.css"), css],
    [path.join(root, "vue", "_shared36", "plugin-colors.js"), colors],
    [path.join(root, "src", "_shared", "05-family-css.js"), jsModule(css)],
  ];
  const svc = serviceDir();
  if (svc) {
    for (const d of ["dwc-src", "dwc36"]) {
      out.push([path.join(svc, d, "family.css"), css]);
      out.push([path.join(svc, d, "plugin-colors.js"), colors]);
    }
  }
  return out;
}

if (require.main === module) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, text] of targets()) {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (cur === text) continue;
    stale++;
    if (check) console.log("out of date: " + file);
    else {
      fs.writeFileSync(file, text);
      console.log("written: " + (file.startsWith(root) ? rel(file) : file));
    }
  }
  if (check && stale) process.exit(1);
  if (!stale) console.log("family: all copies up to date");
}

module.exports = { serviceDir, targets, jsModule };
